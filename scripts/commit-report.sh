#!/usr/bin/env bash
# Commit the build report and the page-hash state to main with [skip ci].
# Nothing else is ever committed by the build: no SeatGeek data, no site files.
#
# Two runs can build the same commit back to back (GitHub sometimes starts
# two runs for one push; a schedule can fire right after a push). The second
# run's checkout is then behind main by the first run's report commit, and
# both runs rewrite the same two files, so a rebase always conflicts. Instead
# of rebasing, each attempt starts from the current tip of main and puts this
# build's two files on top. These files are wholly regenerated by every build,
# so the newest build's copy is the right one.
set -euo pipefail

if [ "${GITHUB_ACTIONS:-}" != "true" ]; then
  echo "commit-report: CI only (it resets the checkout to origin/main)" >&2
  exit 1
fi

FILES=(reports/last-build.md state/page-hashes.json)
SAVED="$(mktemp -d)"
trap 'rm -rf "$SAVED"' EXIT
for f in "${FILES[@]}"; do
  mkdir -p "$SAVED/$(dirname "$f")"
  cp "$f" "$SAVED/$f"
done

git config user.name "github-actions[bot]"
git config user.email "41898282+github-actions[bot]@users.noreply.github.com"
for attempt in 1 2 3; do
  git fetch -q origin main
  git reset -q --hard origin/main
  for f in "${FILES[@]}"; do
    mkdir -p "$(dirname "$f")"
    cp "$SAVED/$f" "$f"
  done
  git add reports/last-build.md state/page-hashes.json
  if git diff --cached --quiet; then
    echo "commit-report: nothing changed"
    exit 0
  fi
  git commit -q -m "Build report $(date -u +'%Y-%m-%d %H:%M UTC') [skip ci]"
  if git push -q origin HEAD:main; then
    echo "commit-report: pushed"
    exit 0
  fi
  sleep $((attempt * 5))
done
echo "commit-report: could not push the report" >&2
exit 1
