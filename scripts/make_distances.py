#!/usr/bin/env python3
"""Write config/distances.json: straight-line miles between every pair of
arenas, from the lat/lon in config/teams.json.

Run it again after editing a coordinate. The road-trip tool ships this table
inside its page; it treats a hop under `drivable_miles` as drivable and
anything longer as a short flight.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def miles(a: dict, b: dict) -> int:
    """Great-circle distance in statute miles, rounded."""
    r = 3958.8
    p1, p2 = math.radians(a["lat"]), math.radians(b["lat"])
    dp = p2 - p1
    dl = math.radians(b["lon"] - a["lon"])
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return round(2 * r * math.asin(math.sqrt(h)))


def main() -> None:
    teams = json.loads((ROOT / "config/teams.json").read_text())["teams"]
    codes = sorted(t["code"] for t in teams)
    by = {t["code"]: t for t in teams}
    table = {a: {b: miles(by[a], by[b]) for b in codes} for a in codes}
    out = {
        "_note": "Straight-line miles between arenas, generated by scripts/make_distances.py "
                 "from config/teams.json. Driving distance is usually 10-25% longer.",
        "drivable_miles": 400,
        "max_hop_miles": 1000,
        "miles": table,
    }
    lines = ",\n".join(f'    "{a}": {json.dumps(table[a], separators=(",", ":"))}' for a in codes)
    head = json.dumps({k: v for k, v in out.items() if k != "miles"}, indent=2)[:-2]
    (ROOT / "config/distances.json").write_text(head + ',\n  "miles": {\n' + lines + "\n  }\n}\n")


if __name__ == "__main__":
    main()
